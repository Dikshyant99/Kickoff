package com.kickoff.model;

public class groundslot {
    private int slotId;
    private int groundId;
    private String slotDate;
    private String startTime;
    private String endTime;
    private String status;

    public groundslot() {}

    public int getSlotId()
    { return slotId; }
    public void setSlotId(int v)
    { this.slotId = v; }
    public int getGroundId()
    { return groundId; }
    public void setGroundId(int v)
    { this.groundId = v; }
    public String getSlotDate()
    { return slotDate; }
    public void setSlotDate(String v)
    { this.slotDate = v; }
    public String getStartTime()

    { return startTime; }
    public void setStartTime(String v)
    { this.startTime = v; }
    public String getEndTime()
    { return endTime; }
    public void setEndTime(String v)
    { this.endTime = v; }
    public String getStatus()
    { return status; }
    public void setStatus(String v)
    { this.status = v; }
}

